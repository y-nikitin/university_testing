from typing import Protocol
from .models import Equipment, RentalOrder, RentalStatus

class EquipmentRepository(Protocol):
    def create(self, equipment: Equipment) -> Equipment: ...
    def find_by_id(self, equipment_id: int) -> Equipment | None: ...
    def update(self, equipment: Equipment) -> None: ...
    def delete(self, equipment_id: int) -> None: ...

class RentalRepository(Protocol):
    def create(self, rental: RentalOrder) -> RentalOrder: ...
    def find_by_id(self, rental_id: int) -> RentalOrder | None: ...
    def find_rentals(self, equipment_id: int, status: RentalStatus) -> list[RentalOrder]: ...
    def mark_returned(self, rental_id: int, late_fee: int) -> None: ...
    def delete(self, rental_id: int) -> None: ...

class RentalPolicy(Protocol):
    def is_allowed(self, equipment: Equipment, quantity: int, days: int) -> bool: ...
