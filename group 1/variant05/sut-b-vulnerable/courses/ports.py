from typing import Protocol
from .models import Student, Course, Enrollment, EnrollmentStatus

class StudentRepository(Protocol):
    def create(self, student: Student) -> Student: ...
    def find_by_id(self, student_id: int) -> Student | None: ...
    def update(self, student: Student) -> None: ...
    def delete(self, student_id: int) -> None: ...

class CourseRepository(Protocol):
    def create(self, course: Course) -> Course: ...
    def find_by_id(self, course_id: int) -> Course | None: ...
    def update(self, course: Course) -> None: ...
    def delete(self, course_id: int) -> None: ...

class EnrollmentRepository(Protocol):
    def create(self, enrollment: Enrollment) -> Enrollment: ...
    def find_by_id(self, enrollment_id: int) -> Enrollment | None: ...
    def find_enrollments(self, course_id: int, status: EnrollmentStatus) -> list[Enrollment]: ...
    def count_occupied(self, course_id: int) -> int: ...
    def has_enrollment(self, student_id: int, course_id: int) -> bool: ...
    def update_status(self, enrollment_id: int, next_status: EnrollmentStatus, refund: int) -> None: ...
    def delete(self, enrollment_id: int) -> None: ...

class EnrollmentPolicy(Protocol):
    def is_allowed(self, student: Student, course: Course) -> bool: ...
