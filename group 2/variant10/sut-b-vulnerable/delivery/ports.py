from typing import Protocol
from .models import Customer, Parcel, Shipment, ShipmentStatus

class CustomerRepository(Protocol):
    def create(self, customer: Customer) -> Customer: ...
    def find_by_id(self, customer_id: int) -> Customer | None: ...
    def update(self, customer: Customer) -> None: ...
    def delete(self, customer_id: int) -> None: ...

class ParcelRepository(Protocol):
    def create(self, parcel: Parcel) -> Parcel: ...
    def find_by_id(self, parcel_id: int) -> Parcel | None: ...
    def update(self, parcel: Parcel) -> None: ...
    def delete(self, parcel_id: int) -> None: ...

class ShipmentRepository(Protocol):
    def create(self, shipment: Shipment) -> Shipment: ...
    def find_by_id(self, shipment_id: int) -> Shipment | None: ...
    def find_shipments(self, customer_id: int, status: ShipmentStatus) -> list[Shipment]: ...
    def update_status(self, shipment_id: int, expected: ShipmentStatus, next_status: ShipmentStatus) -> None: ...
    def delete(self, shipment_id: int) -> None: ...

class ShippingPolicy(Protocol):
    def is_allowed(self, customer: Customer, parcel: Parcel, distance_km: int) -> bool: ...
