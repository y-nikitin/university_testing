from typing import Protocol
from datetime import date
from .models import Room, Booking, BookingStatus

class RoomRepository(Protocol):
    def create(self, room: Room) -> Room: ...
    def find_by_id(self, room_id: int) -> Room | None: ...
    def update(self, room: Room) -> None: ...
    def delete(self, room_id: int) -> None: ...

class BookingRepository(Protocol):
    def create(self, booking: Booking) -> Booking: ...
    def find_by_id(self, booking_id: int) -> Booking | None: ...
    def is_available(self, room_id: int, check_in: date, check_out: date) -> bool: ...
    def find_bookings(self, room_id: int, status: BookingStatus) -> list[Booking]: ...
    def cancel(self, booking_id: int, refund: int) -> None: ...
    def delete(self, booking_id: int) -> None: ...

class BookingPolicy(Protocol):
    def is_allowed(self, room: Room, guests: int, nights: int) -> bool: ...
